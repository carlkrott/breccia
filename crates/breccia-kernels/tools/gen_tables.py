#!/usr/bin/env python3
"""Regenerate the IQ quant tables from the ggml reference headers.

The grid/sign/value tables are *data* from llama.cpp (MIT); they are copied
verbatim into two generated files so that neither the shaders nor the CPU
reference re-derive them:

    src/tables.rs               -> the same data for the CPU reference *and* the
                                   u32 word layout the kernels upload as their
                                   `QuantTables` storage buffer (binding 3)

Usage:
    python3 tools/gen_tables.py [path-to-ggml-common.h]

Default source:
    Reference Projects/llama.cpp/ggml/src/ggml-common.h
(the clone recorded in docs/reference-engines.md; upstream llama.cpp commit
6050b46 for the fork that adds Q1_0/Q2_0).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(CRATE))

DEFAULT_SRC = os.path.join(
    REPO, "Reference Projects", "llama.cpp", "ggml", "src", "ggml-common.h"
)

# (C name, element type, expected count)
TABLES = [
    ("ksigns_iq2xs", "uint8_t", 128),
    ("iq2xxs_grid", "uint64_t", 256),
    ("iq2xs_grid", "uint64_t", 512),
    ("iq3xxs_grid", "uint32_t", 256),
    ("iq3s_grid", "uint32_t", 512),
    ("iq2s_grid", "uint64_t", 1024),
    ("kvalues_iq4nl", "int8_t", 16),
]


def parse(path):
    text = open(path, encoding="utf-8").read()
    out = {}
    for name, ctype, count in TABLES:
        m = re.search(
            r"GGML_TABLE_BEGIN\(%s,\s*%s,\s*(\d+)\)(.*?)GGML_TABLE_END"
            % (re.escape(ctype), re.escape(name)),
            text,
            re.S,
        )
        if not m:
            raise SystemExit(f"table {name} not found in {path}")
        declared = int(m.group(1))
        body = re.sub(r"//[^\n]*", "", m.group(2))
        vals = [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]
        if len(vals) != count or declared != count:
            raise SystemExit(
                f"{name}: parsed {len(vals)} values, header declares {declared}, "
                f"generator expects {count}"
            )
        out[name] = (ctype, vals)
    return out


HEADER = """\
// GENERATED by tools/gen_tables.py from llama.cpp ggml-common.h — do not edit.
// Tables are data from llama.cpp (MIT License), commit 6050b46.
"""


# GPU table buffer layout (u32 words). MUST match the TBL_*_BASE defines in
# shaders/blocks.glsl; `tables::tests::gpu_layout_matches_the_shader` checks it.
GPU_LAYOUT = [
    ("TBL_IQ2XXS_LO", "iq2xxs_grid", "lo"),
    ("TBL_IQ2XXS_HI", "iq2xxs_grid", "hi"),
    ("TBL_IQ2XS_LO", "iq2xs_grid", "lo"),
    ("TBL_IQ2XS_HI", "iq2xs_grid", "hi"),
    ("TBL_IQ3XXS_GRID", "iq3xxs_grid", "u32"),
    ("TBL_IQ3S_GRID", "iq3s_grid", "u32"),
    ("TBL_SIGNS", "ksigns_iq2xs", "u32"),
    ("TBL_IQ4NL_VALUES", "kvalues_iq4nl", "i32"),
    # Appended after the tables the first kernel pass shipped, so no existing
    # TBL_* offset moved (the shader defines are checked against these).
    ("TBL_IQ2S_LO", "iq2s_grid", "lo"),
    ("TBL_IQ2S_HI", "iq2s_grid", "hi"),
]


def gpu_words(tables):
    out = []
    offsets = []
    for name, src, part in GPU_LAYOUT:
        offsets.append((name, len(out)))
        vals = tables[src][1]
        if part == "lo":
            out.extend(v & 0xFFFFFFFF for v in vals)
        elif part == "hi":
            out.extend(v >> 32 for v in vals)
        else:
            out.extend(v & 0xFFFFFFFF for v in vals)
    return out, offsets


def emit_rust(tables, path):
    lines = [HEADER, "#![allow(dead_code)]\n"]
    for name, (ctype, vals) in tables.items():
        if ctype == "uint64_t":
            ty, fmt = "u64", lambda v: f"0x{v:016x}"
        elif ctype == "uint32_t":
            ty, fmt = "u32", lambda v: f"0x{v:08x}"
        elif ctype == "uint8_t":
            ty, fmt = "u8", lambda v: str(v)
        else:
            ty, fmt = "i8", lambda v: str(v)
        # `static` for the big data tables: a 4096+ element `const` array is
        # copied at every use site and trips clippy::large_const_arrays.
        kind = "static" if len(vals) > 512 else "const"
        lines.append(f"pub {kind} {name.upper()}: [{ty}; {len(vals)}] = [")
        body = ",\n".join(
            "    " + ", ".join(fmt(v) for v in vals[i : i + 8])
            for i in range(0, len(vals), 8)
        )
        lines.append(body + ",\n];\n")
    words, offsets = gpu_words(tables)
    for name, off in offsets:
        lines.append(f"pub const {name}: usize = {off};")
    lines.append(f"\npub const GPU_TABLE_WORDS_LEN: usize = {len(words)};\n")
    lines.append("pub static GPU_TABLE_WORDS: [u32; GPU_TABLE_WORDS_LEN] = [")
    body = ",\n".join(
        "    " + ", ".join(f"0x{v:08x}" for v in words[i : i + 8])
        for i in range(0, len(words), 8)
    )
    lines.append(body + ",\n];\n")
    open(path, "w", encoding="utf-8").write("\n".join(lines))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    tables = parse(src)
    emit_rust(tables, os.path.join(CRATE, "src", "tables.rs"))
    print(f"regenerated tables from {src}")


if __name__ == "__main__":
    main()
